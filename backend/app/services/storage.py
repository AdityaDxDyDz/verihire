"""Storage for original PDFs.

* ``LocalStorage`` (dev/tests): files under LOCAL_STORAGE_DIR; signed URLs are HMAC-SHA256 tokens
  served by ``GET /api/v1/files/local`` (an <iframe> cannot send a Bearer header, so the
  signature *is* the authorisation, and it expires).
* ``SupabaseStorage`` (production): private bucket, service key stays on the server, streamed
  downloads with a size cap, short-lived signed URLs.

Keys are generated by the backend (``<owner-hash>/<document-uuid>.pdf``), never from user file names,
and are validated against path traversal anyway.
"""

from __future__ import annotations

import asyncio
import base64
import hashlib
import hmac
import re
import time
from pathlib import Path
from urllib.parse import quote

import httpx

from ..errors import AppError

_KEY_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}(?:/[A-Za-z0-9_-]{1,64})*\.pdf$")


class StorageError(Exception):
    pass


def validate_key(key: str) -> str:
    if not _KEY_RE.match(key or "") or ".." in key or key.startswith("/"):
        raise StorageError(f"invalid storage key: {key!r}")
    return key


def make_key(owner_id: str, document_id: str) -> str:
    owner = hashlib.sha256(owner_id.encode()).hexdigest()[:24]
    return validate_key(f"{owner}/{document_id}.pdf")


class Storage:
    mode = "abstract"

    async def put(self, key: str, data: bytes) -> None: raise NotImplementedError
    async def get(self, key: str, max_bytes: int) -> bytes: raise NotImplementedError
    async def delete(self, key: str) -> None: raise NotImplementedError
    async def signed_url(self, key: str, expires_in: int) -> str: raise NotImplementedError
    async def close(self) -> None: return None


class LocalStorage(Storage):
    mode = "local"

    def __init__(self, root: str | Path, secret: str, url_prefix: str = "/api/v1/files/local", clock=time.time):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        self.secret = secret.encode()
        self.url_prefix = url_prefix
        self.clock = clock

    def _path(self, key: str) -> Path:
        p = (self.root / validate_key(key)).resolve()
        if self.root not in p.parents:
            raise StorageError("path escapes storage root")
        return p

    async def put(self, key: str, data: bytes) -> None:
        p = self._path(key)

        def _write() -> None:
            p.parent.mkdir(parents=True, exist_ok=True)
            tmp = p.with_suffix(".tmp")
            tmp.write_bytes(data)
            tmp.replace(p)  # atomic

        await asyncio.to_thread(_write)

    async def get(self, key: str, max_bytes: int) -> bytes:
        p = self._path(key)
        if not p.exists():
            raise StorageError("object not found")
        if p.stat().st_size > max_bytes:
            raise StorageError("object larger than allowed")
        return await asyncio.to_thread(p.read_bytes)

    async def delete(self, key: str) -> None:
        p = self._path(key)
        await asyncio.to_thread(lambda: p.unlink(missing_ok=True))

    def _sign(self, key: str, exp: int) -> str:
        mac = hmac.new(self.secret, f"{key}|{exp}".encode(), hashlib.sha256).digest()
        return base64.urlsafe_b64encode(mac).decode().rstrip("=")

    async def signed_url(self, key: str, expires_in: int) -> str:
        validate_key(key)
        exp = int(self.clock()) + expires_in
        return f"{self.url_prefix}?key={quote(key, safe='')}&exp={exp}&sig={self._sign(key, exp)}"

    def verify(self, key: str, exp: int, sig: str) -> Path:
        """Check a signed URL; raise 404 (never 403) on any problem."""
        try:
            validate_key(key)
        except StorageError:
            raise AppError(404, "not_found", "File not found") from None
        good = self._sign(key, exp)
        if not hmac.compare_digest(good, sig or "") or exp < int(self.clock()):
            raise AppError(404, "not_found", "Link expired or invalid")
        p = self._path(key)
        if not p.exists():
            raise AppError(404, "not_found", "File not found")
        return p


class SupabaseStorage(Storage):
    mode = "supabase"

    def __init__(self, url: str, service_key: str, bucket: str, http: httpx.AsyncClient | None = None):
        self.base = url.rstrip("/") + "/storage/v1"
        self.bucket = bucket
        self.headers = {"Authorization": f"Bearer {service_key}", "apikey": service_key}
        self.http = http or httpx.AsyncClient(timeout=httpx.Timeout(30, connect=10))

    async def close(self) -> None:
        await self.http.aclose()

    def _obj(self, key: str) -> str:
        return f"{self.base}/object/{self.bucket}/{validate_key(key)}"

    async def put(self, key: str, data: bytes) -> None:
        r = await self.http.post(self._obj(key), content=data,
                                 headers={**self.headers, "Content-Type": "application/pdf", "x-upsert": "true"})
        if r.status_code >= 300:
            raise StorageError(f"upload failed ({r.status_code})")

    async def get(self, key: str, max_bytes: int) -> bytes:
        buf = bytearray()
        async with self.http.stream("GET", self._obj(key), headers=self.headers) as r:
            if r.status_code != 200:
                raise StorageError(f"download failed ({r.status_code})")
            async for part in r.aiter_bytes():
                buf += part
                if len(buf) > max_bytes:
                    raise StorageError("object larger than allowed")
        return bytes(buf)

    async def delete(self, key: str) -> None:
        r = await self.http.request("DELETE", f"{self.base}/object/{self.bucket}",
                                    json={"prefixes": [validate_key(key)]}, headers=self.headers)
        if r.status_code >= 300 and r.status_code != 404:
            raise StorageError(f"delete failed ({r.status_code})")

    async def signed_url(self, key: str, expires_in: int) -> str:
        r = await self.http.post(f"{self.base}/object/sign/{self.bucket}/{validate_key(key)}",
                                 json={"expiresIn": expires_in}, headers=self.headers)
        if r.status_code != 200:
            raise StorageError(f"sign failed ({r.status_code})")
        signed = r.json().get("signedURL") or r.json().get("signedUrl")
        if not signed:
            raise StorageError("sign response missing URL")
        return signed if signed.startswith("http") else f"{self.base}{signed}"


def build_storage(settings) -> Storage:
    if settings.STORAGE_MODE == "supabase":
        return SupabaseStorage(settings.SUPABASE_URL, settings.SUPABASE_SERVICE_KEY, settings.STORAGE_BUCKET)
    return LocalStorage(settings.LOCAL_STORAGE_DIR, settings.APP_SECRET)
